/**
 * 依代碼或名稱關鍵字搜尋職類
 * @param {string} keyword
 * @returns {Array<{code: string, name: string, group: string}>}
 */
window.searchJobCategories = function (keyword) {
  if (!keyword) return window.JOB_CATEGORIES;
  const k = String(keyword).trim().toLowerCase();
  return window.JOB_CATEGORIES.filter(
    (j) =>
      j.code.toLowerCase().includes(k) ||
      j.name.toLowerCase().includes(k) ||
      (j.group && j.group.toLowerCase().includes(k))
  );
};

/**
 * 依代碼取得職類完整資料
 */
window.getJobCategoryByCode = function (code) {
  if (!code) return null;
  const c = String(code).trim();
  return window.JOB_CATEGORIES.find((j) => j.code === c) || null;
};
